#ifndef __NVS_H__
#define __NVS_H__

#include <stdint.h>

/*
  Flash 参数存储(模拟 NVS,文档《03》§6.1)

  双区轮换防掉电写坏:
    区 A: 0x0800F000  区 B: 0x0800F800(各占一页 2KB)
    保存永远写"对侧区":先擦后写,写完校验;掉电发生在任意时刻,
    至少有一个区是完整的。上电取"序号大且校验通过"的区为最新参数。

  注:文档写的"页4 (0x0800F000)"页码有误——RCT6 是高密度器件,
     页大小 2KB,0x0800F000 实际是第 30 页(0xF000/0x800=30),
     实现按文档给的地址用,离程序区(约 40KB 内)很远,互不干扰。
*/

/* NVS 版本号:参数结构(param_payload_t)变动时加 1,旧 Flash 数据自动作废 */
#define NVS_VERSION  1

void NVS_Init(void);    /* 上电初始化:读双区取最新有效参数载入 param;
                           两区全无效(首次上电/被擦) → 用默认值并立即落一份盘 */
void NVS_Tick(void);    /* 落盘调度(控制任务 100ms 调):有参数变更时防抖 2s,
                           期间无新写入才真正擦写 Flash(远程整定连续写多个
                           寄存器只触发最后一次落盘,不频繁擦 Flash) */

#endif
